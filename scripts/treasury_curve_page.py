#!/usr/bin/env python3
"""Render the treasury curve verdict page from the face that decides it.

The page research/TREASURY_CURVE_VERDICT.md used to carry hand-copied digits: the
criteria table, the halves, the out-of-sample line, the robustness grid. r1859 had to
re-align every one of them because the face had moved from 2383 bars (to 11-13) to 2387
(to 11-19), and a page one generation behind its own face reads exactly like a page that
is telling the truth. The r1691 smoke leg could only catch the two numbers it knew how
to look for.

So the readings move into a generated block between two markers. The prose stays prose;
every number in it comes from results/treasury_curve_spread.json:

    python scripts/treasury_curve_page.py --write   # re-render the block in place
    python scripts/treasury_curve_page.py --check   # rc0 = block equals the face
    python scripts/treasury_curve_page.py --selftest

--check is the gate the smoke leg drives: it rebuilds the block from the face and
compares bytes, so a hand-edit inside the markers fails instead of becoming the new truth.
Percent fields in the face are already percent (ann_pct = -9.5881 means -9.59%); they are
never rescaled here, because the two readings that look alike and differ by 100x are the
expensive kind of silent error (E683).
"""
from __future__ import annotations

import argparse
import io
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FACE = os.path.join(ROOT, "results", "treasury_curve_spread.json")
PAGE = os.path.join(ROOT, "research", "TREASURY_CURVE_VERDICT.md")

BEGIN = "<!-- TREASURY-CURVE-READING:BEGIN"
END = "<!-- TREASURY-CURVE-READING:END -->"


def _sgn(x, digits=2):
    return ("%+." + str(digits) + "f") % x


def _txt(x, digits=2):
    return ("%." + str(digits) + "f") % x


def _has(passed):
    return "过" if passed else "败"


def reading_block(face):
    """Build the whole generated block, markers included, from the face alone."""
    c = face["verdict"]["criteria"]
    m = face["meta"]
    grid = face["robustness_grid"]
    halves = face["halves"]
    oos = face["oos_2024"]
    full = face["full"]

    best = max(grid["cells"], key=lambda cell: cell["ann_pct"])
    worst = min(grid["cells"], key=lambda cell: cell["ann_pct"])
    best_where = "z=%s/h=%d" % (_txt(best["z_enter"], 1), best["max_hold"])

    i1 = c["C1_capital_ann_ge_3pct"]
    i2 = c["C2_oos_sharpe_ge_0.70"]
    i3 = c["C3_permutation_p_lt_0.05"]
    diag = c["diagnostic_halves_same_sign"]

    lines = [
        BEGIN + " (generated by scripts/treasury_curve_page.py --write from "
        "results/treasury_curve_spread.json; do not edit by hand) -->",
        "证据 cutoff %s · %d 根 bar · %s → %s · 换手 %d 次 · 在场 %.2f%%："
        % (face["evidence_cutoff"], m["bars"], m["first"], m["last"],
           m["turnovers"], m["in_market_share"] * 100.0),
        "",
        "| 判据 | 冻结阈值 | 读数 | 判 |",
        "|---|---|---|---|",
        "| C1 资金口径成本后年化 | ≥ %.2f%%/yr | **%s%%** | %s |"
        % (i1["threshold"], _sgn(i1["value"]), _has(i1["pass"])),
        "| C2 样本外（2024-01-01 起）夏普 | ≥ %.2f | **%s** | %s |"
        % (i2["threshold"], _sgn(i2["value"]), _has(i2["pass"])),
        "| C3 置换对照（%d 次旋转，同持仓结构） | p < %.2f | **p = %.3f** | %s |"
        % (face["permutation"]["trials"], i3["threshold"], i3["value"], _has(i3["pass"])),
        "| 诊断·前后半场同号（无否决权） | — | 前半 **%s%%** / 后半 **%s%%** | %s |"
        % (_sgn(diag["h1_pct"]), _sgn(diag["h2_pct"]), _has(diag["pass"])),
        "",
        "分段与稳健性（同块派生）：",
        "",
        "- 全窗：年化 %s%% · 夏普 %s · 回撤 %s%% · n=%d"
        % (_sgn(full["ann_pct"]), _sgn(full["sharpe"]), _sgn(full["mdd_pct"]), full["n"]),
        "- 前半 %s→%s：年化 %s%% · n=%d"
        % (halves["h1"]["from"], halves["h1"]["to"], _sgn(halves["h1"]["ann_pct"]),
           halves["h1"]["n"]),
        "- 后半 %s→%s：年化 %s%% · n=%d"
        % (halves["h2"]["from"], halves["h2"]["to"], _sgn(halves["h2"]["ann_pct"]),
           halves["h2"]["n"]),
        "- 样本外 2024 起：年化 %s%% · 夏普 %s · 回撤 %s%% · n=%d"
        % (_sgn(oos["ann_pct"]), _sgn(oos["sharpe"]), _sgn(oos["mdd_pct"]), oos["n"]),
        "- 稳健性网格 %d 格：最好 %s%%（%s）· 最差 %s%% · 正格 %d"
        % (grid["n_cells"], _sgn(best["ann_pct"]), best_where,
           _sgn(worst["ann_pct"]), grid["positive_cells"]),
        "- roll 日：T %d 天 / TF %d 天 · 幻影点数剔除 %s"
        % (m["t_roll_days"], m["tf_roll_days"], _txt(m["phantom_points_dropped"])),
        "- 裁决：**%s**%s" % (face["verdict"]["verdict"],
                             "（三条判据全败，没有任何一条是差一点）"
                             if face["verdict"]["verdict"] == "KILL" else ""),
        END,
    ]
    return "\n".join(lines)


def _span(text):
    i = text.find(BEGIN)
    if i < 0:
        raise ValueError("BEGIN marker missing")
    j = text.find(END, i)
    if j < 0:
        raise ValueError("END marker missing")
    return i, j + len(END)


def splice(text, face):
    i, j = _span(text)
    return text[:i] + reading_block(face) + text[j:]


def compare(page_text, face):
    """(ok, message): the block in the page must be byte-identical to the face's."""
    try:
        i, j = _span(page_text)
    except ValueError as exc:
        return False, str(exc)
    expected = reading_block(face)
    found = page_text[i:j]
    if found == expected:
        return True, "block matches face (%d chars)" % len(expected)
    exp_lines = expected.splitlines()
    got_lines = found.splitlines()
    for n, (a, b) in enumerate(zip(exp_lines, got_lines), 1):
        if a != b:
            return False, "line %d drifted: page=%r face=%r" % (n, b[:120], a[:120])
    return False, "block length differs: page=%d face=%d lines" % (len(got_lines),
                                                                  len(exp_lines))


def _load(path):
    with io.open(path, encoding="utf-8") as fh:
        return json.load(fh)


def _selftest():
    face = _load(FACE)
    block = reading_block(face)
    checks = []

    def one(name, cond, detail=""):
        checks.append((name, bool(cond), detail))

    c = face["verdict"]["criteria"]
    one("block carries the verdict verb",
        ("**%s**" % face["verdict"]["verdict"]) in block)
    one("percent fields print as percent, not rescaled (E683)",
        ("%s%%" % _sgn(c["C1_capital_ann_ge_3pct"]["value"])) in block
        and ("%s" % _sgn(c["C1_capital_ann_ge_3pct"]["value"] * 100.0)) not in block)
    one("block is derived, not copied: changing the face changes the block",
        reading_block(_mutate(face, -1.0)) != block)
    one("block names the evidence cutoff",
        face["evidence_cutoff"] in block)

    good = "head\n" + block + "\ntail\n"
    ok, msg = compare(good, face)
    one("matching page passes", ok, msg)

    tampered = good.replace("%s%%" % _sgn(c["C1_capital_ann_ge_3pct"]["value"]),
                            "%s%%" % _sgn(c["C1_capital_ann_ge_3pct"]["value"] + 1.0))
    ok, msg = compare(tampered, face)
    one("a single hand-edited digit fails", not ok, msg)

    one("page without markers refuses", compare("no markers here", face)[0] is False)

    moved = splice("head\n" + block + "\ntail\n", _mutate(face, -1.0))
    one("splice leaves prose outside the markers untouched",
        moved.startswith("head\n") and moved.endswith("\ntail\n"))

    passed = sum(1 for _, okk, _ in checks if okk)
    for name, okk, detail in checks:
        print("[%s] %s%s" % ("PASS" if okk else "FAIL", name,
                             (" — " + detail) if (detail and not okk) else ""))
    print("treasury_curve_page selftest %d/%d" % (passed, len(checks)))
    return 0 if passed == len(checks) else 3


def _mutate(face, delta):
    """Copy of the face with one reading moved, so 'derived' can be told from 'copied'."""
    out = json.loads(json.dumps(face))
    out["verdict"]["criteria"]["C1_capital_ann_ge_3pct"]["value"] += delta
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true", help="re-render the block in place")
    ap.add_argument("--check", action="store_true", help="verify the page against the face")
    ap.add_argument("--selftest", action="store_true", help="offline self-test")
    args = ap.parse_args(argv)

    if args.selftest:
        return _selftest()

    face = _load(FACE)
    with io.open(PAGE, encoding="utf-8", newline="") as fh:
        page = fh.read()

    if args.write:
        new = splice(page, face)
        if new != page:
            with io.open(PAGE, "w", encoding="utf-8", newline="") as fh:
                fh.write(new)
            print("PAGE-WRITTEN %s" % os.path.relpath(PAGE, ROOT))
        else:
            print("NO-CHANGE block already matches the face")
        return 0

    ok, msg = compare(page, face)
    print("%s %s" % ("CHECK_OK" if ok else "CHECK_STALE", msg))
    return 0 if ok else 3


if __name__ == "__main__":
    sys.exit(main())
