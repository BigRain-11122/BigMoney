import subprocess, json, hashlib, datetime

def show(ref, path):
    r = subprocess.run(['git', 'show', ref + ':' + path], capture_output=True)
    return r.stdout

def jd(b):
    return json.loads(b.decode('utf-8'))

def sha(o):
    return hashlib.sha256(json.dumps(o, sort_keys=True).encode()).hexdigest()

path = 'results/compute_audit.json'
pre = jd(show('7ffcd2011', path))
cur_bytes = open(path, 'rb').read()
cur = jd(cur_bytes)

pre_rows = {sha(r): r for r in pre['history']}
cur_rows = {sha(r): r for r in cur['history']}
lost = [pre_rows[h] for h in sorted(set(pre_rows) - set(cur_rows))]
print('lost rows to heal:', len(lost))

if not lost:
    receipt = {"round": "r799", "machine": "bm-b", "action": "heal-no-op",
               "reason": "no lost rows found", "ts": datetime.datetime.now().isoformat(timespec='seconds')}
    json.dump(receipt, open('results/_r799bmb_heal_receipt.json', 'w', encoding='utf-8'), indent=2, ensure_ascii=False)
    print('no-op receipt written')
    raise SystemExit(0)

# append-only ledger: insert by ts order (lost row ts 06:06:33 > all current -> tail append)
for r in lost:
    cur['history'].append(r)
assert all(cur['history'][i]['ts'] <= cur['history'][i + 1]['ts'] for i in range(len(cur['history']) - 1)), 'ts order broken'

new_rows = {sha(r): r for r in cur['history']}
assert set(new_rows) == set(cur_rows) | {sha(r) for r in lost}, 'row-set identity broken'
assert len(cur['history']) == len(cur_rows) + len(lost), 'count broken'

with open(path, 'w', encoding='utf-8') as f:
    json.dump(cur, f, indent=2, ensure_ascii=False)

# verify re-read
back = jd(open(path, 'rb').read())
assert len(back['history']) == len(cur['history'])
receipt = {
    "round": "r799", "machine": "bm-b", "action": "compute_audit history heal",
    "law": "r798 tail heal pointer; S0 reland ring law (per-face union)",
    "source": "pre-rebase 7ffcd2011:results/compute_audit.json",
    "rows_healed": len(lost),
    "healed_ts": [r['ts'] for r in lost],
    "history_len_before": len(cur_rows), "history_len_after": len(back['history']),
    "row_set_identity": "assert PASS (after == before | lost)",
    "ts_order_assert": "PASS",
    "regime_state_face": "non-append-only shadow snapshot; regenerated by S6 market_regime.py each round; no surgery needed (S6 re-derive heals)",
    "ts": datetime.datetime.now().isoformat(timespec='seconds'),
}
json.dump(receipt, open('results/_r799bmb_heal_receipt.json', 'w', encoding='utf-8'), indent=2, ensure_ascii=False)
print('healed', len(lost), 'row(s); receipt written; history', len(cur_rows), '->', len(back['history']))
